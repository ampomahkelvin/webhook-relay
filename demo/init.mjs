// demo/init.mjs — one-shot demo bootstrap (DEMO section 6 of PLAN).
//
// Runs after `api` is healthy and does everything the demo script's first
// steps would do by hand:
//
//   1. waits for the API,
//   2. creates the demo tenant + API key,
//   3. registers two endpoints on the compose receiver — a fast one and a
//      deliberately slow one (?delayMs=1500) — and carries the
//      server-generated signing secrets to the receiver through the
//      `demo-secrets` volume, since the receiver may already be running.
//   4. writes ./demo/demo-credentials.txt for the host (the API key and
//      secrets are shown only once).
//
// `docker compose up` gives you the full running demo plus credentials —
// the manual walkthrough (README "Take it for a spin") starts from there.

import { writeFile } from 'node:fs/promises'

const API_BASE = process.env['API_BASE_URL'] ?? `http://api:${process.env['PORT'] ?? 3000}`
const ADMIN_KEY = process.env['ADMIN_API_KEY']
if (!ADMIN_KEY) {
  console.error('ADMIN_API_KEY is not set')
  process.exit(1)
}

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))

async function waitForApi() {
  const deadline = Date.now() + 180_000
  for (;;) {
    try {
      const response = await fetch(`${API_BASE}/health`)
      if (response.ok) return
    } catch {
      // api not up yet
    }
    if (Date.now() > deadline) throw new Error(`API never became healthy at ${API_BASE}`)
    await sleep(1000)
  }
  throw new Error('unreachable')
}

async function call(method, path, body, token) {
  const response = await fetch(`${API_BASE}${path}`, {
    method,
    headers: {
      Authorization: `Bearer ${token ?? ADMIN_KEY}`,
      'Content-Type': 'application/json',
      ...(body !== undefined ? { 'Idempotency-Key': `demo-init-${path}-${Date.now()}` } : {}),
    },
    body: body === undefined ? undefined : JSON.stringify(body),
  })
  if (!response.ok) {
    const text = await response.text()
    throw new Error(`${method} ${path} -> ${response.status}: ${text}`)
  }
  const data = await response.json()
  console.log(`${method} ${path} -> ${response.status}`)
  return data
}

const receiverSecrets = []

async function makeEndpoint(label, url) {
  const response = await call('POST', '/v1/endpoints', { url, eventTypes: ['*'] }, tenantApiKey)
  receiverSecrets.push(response.signingSecret)
  return response
}

await waitForApi()
const tenant = await call('POST', '/admin/tenants', { name: 'demo' })
const apiKey = tenant.apiKey.key
const tenantApiKey = apiKey
const fast = await makeEndpoint('fast', 'http://receiver:9000/hook')
const slow = await makeEndpoint('slow', 'http://receiver:9000/hook?delayMs=1500')

// Hand the receiver its secrets (it re-reads this file per delivery).
await writeFile('/run/demo/secrets', receiverSecrets.join('\n') + '\n')

// Same credentials for the host: the README walkthrough references them.
await writeFile(
  '/out/demo-credentials.txt',
  `# Generated by demo/init.mjs on ${new Date().toISOString()}
# The API key and signing secrets are shown only once; keep this file local.

API_KEY=${apiKey}
TENANT_ID=${tenant.tenant.id}
ENDPOINT_ID_FAST=${fast.endpoint.id}
ENDPOINT_ID_SLOW=${slow.endpoint.id}
# receiver URLs (from inside the compose network):
#   fast: http://receiver:9000/hook
#   slow: http://receiver:9000/hook?delayMs=1500
`,
)

console.log('')
console.log('demo ready — credentials in ./demo/demo-credentials.txt')
console.log('open Grafana at http://localhost:3001 (login admin/admin)')
